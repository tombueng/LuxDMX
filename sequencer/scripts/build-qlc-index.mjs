// Builds public/qlc/index.json from QLC+'s FixturesMap.xml at a pinned commit: 1781 fixture
// definitions (Apache-2.0). The app searches this and fetches one .qxf from raw.githubusercontent
// (CORS allowed) when you add it.
//   node scripts/build-qlc-index.mjs [commit]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = process.argv[2];
const sha = arg ?? (await (await fetch('https://api.github.com/repos/mcallegari/qlcplus/commits/master')).json()).sha;
const xml = await (await fetch(`https://raw.githubusercontent.com/mcallegari/qlcplus/${sha}/resources/fixtures/FixturesMap.xml`)).text();
const fixtures = [];
for (const m of xml.matchAll(/<M n="([^"]+)">([\s\S]*?)<\/M>/g))
  for (const f of m[2].matchAll(/<F n="([^"]+)" m="([^"]*)"/g))
    fixtures.push({ k: `${m[1]}/${f[1]}.qxf`, n: f[2].replaceAll('&amp;', '&').replaceAll('&quot;', '"'), m: m[1].replaceAll('_', ' ') });
fixtures.sort((a, b) => (a.m + a.n).localeCompare(b.m + b.n));
const out = path.join(root, 'public/qlc');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'index.json'), JSON.stringify({ commit: sha, generated: new Date().toISOString(), fixtures }));
fs.writeFileSync(path.join(out, 'NOTICE'), 'Fixture definitions from Q Light Controller Plus (https://github.com/mcallegari/qlcplus),\nApache License 2.0. Index generated by scripts/build-qlc-index.mjs.\n');
console.log(`QLC+ ${sha}: ${fixtures.length} fixtures -> public/qlc/index.json`);
